export type BotsAppTranslationKey = keyof typeof entries
export type BotsAppLanguage = "english" | "portuguese" | "spanish"

const LANGUAGE_FIELD = { english: "en", portuguese: "pt", spanish: "es" } as const

export function translateBotsApp(
  language: BotsAppLanguage,
  key: BotsAppTranslationKey,
  replacements?: Record<string, string | number>
): string {
  const entry: Entry = entries[key]
  let text = entry[LANGUAGE_FIELD[language]] ?? entry.en
  if (replacements) {
    for (const [name, value] of Object.entries(replacements)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}

