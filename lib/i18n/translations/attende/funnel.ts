export type AttendeFunnelKey = keyof typeof entries
export type AttendeFunnelLanguage = "english" | "portuguese" | "spanish"

const LANGUAGE_FIELD = { english: "en", portuguese: "pt", spanish: "es" } as const

export function translateAttendeFunnel(language: AttendeFunnelLanguage, key: AttendeFunnelKey, replacements?: Record<string, string | number>): string {
  const entry: Entry = entries[key]
  // A missing or empty translation falls back to English, never to the key.
  let text = entry[LANGUAGE_FIELD[language]] || entry.en
  if (replacements) {
    for (const [name, value] of Object.entries(replacements)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}

