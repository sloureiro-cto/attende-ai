export type AgentType = "specialized" | "orchestrator"
export type AgentCategory = "marketing" | "sales" | "support" | "engineering" | "product" | "general" | "custom"

export interface ModelConfig {
  provider: "ollama" | "openai" | "anthropic" | "google"
  model: string
  temperature: number
  maxSteps: number
  maxTokens?: number
}

export interface ToolPermission {
  toolId: string
  allowDestructive: boolean
  requireConfirmation: boolean
}

export interface SkillAttachment {
  skillId: string
  config?: {
    autoApply?: boolean
    priority?: number
    conditional?: {
      enabled: boolean
      condition?: string
    }
  }
}

/** Preset communication voice injected alongside (not replacing) the system prompt. */
export type AgentVoicePreset = "friendly" | "professional" | "concise" | "formal" | "custom"

export interface AgentIdentity {
  displayName?: string
  role?: string
  /** Generated by the onboarding profile generator; part of `identity` on every agent read. */
  persona?: string
  mission?: string
  /** Free-form tone when `voicePreset` is `custom`, or legacy tone string from API. */
  tone?: string
  communicationStyle?: string
  voicePreset?: AgentVoicePreset
  /** Header badge icon key from the Figma library (921:4293). */
  badgeIcon?: string
  /** Header badge background hex from the Figma color grid. */
  badgeColor?: string
}

/**
 * Prioritized reference material for the model (workspace facts, uploads, pinned entities).
 * Nested under `contextConfig` so a single PATCH can update scope + knowledge.
 */
export interface AgentKnowledgeSources {
  /** Plain / simple markdown; server may truncate. */
  freeText?: string
  projectIds?: string[]
  cardIds?: string[]
  documentIds?: string[]
  folderIds?: string[]
  /** Chat / attachment ids when backend supports them */
  attachmentIds?: string[]
  /** Indexed web link KnowledgeSource ids */
  webSourceIds?: string[]
}

export type AgentSetupQuestionType = "text" | "single_choice" | "multi_choice"

/**
 * Publisher-defined onboarding question (e.g. "What's your product?") asked
 * during the agent's first conversation, on top of the platform's baseline
 * onboarding steps. Answers land in `userContextProfile.setupAnswers`.
 */
export interface AgentSetupQuestion {
  /** Stable slug, e.g. 'product'. Used as the answer key and onboarding step key. */
  key: string
  question: string
  hint?: string
  type: AgentSetupQuestionType
  /** Required (and only meaningful) for 'single_choice' / 'multi_choice'. */
  options?: string[]
  required?: boolean
}

export interface AgentIcebreaker {
  text: string
}

export type AgentAccessScope = "workspace" | "private"

export type AgentTtsProvider = "openai" | "elevenlabs"
export type AgentVoiceReplyMode = "off" | "mirror" | "always"
export type AgentVoiceReplyChannel = "whatsapp" | "sms" | "instagram"

export interface AgentVoiceSettings {
  provider: AgentTtsProvider
  /** OpenAI voice name or ElevenLabs voice id. */
  voiceId: string
  model?: string
  /** 0.5–2 (1 = normal). */
  speed?: number
  /** Speaking style (gpt-4o-mini-tts only). */
  instructions?: string
  replyMode: AgentVoiceReplyMode
  /** Omitted = every channel. */
  channels?: AgentVoiceReplyChannel[]
  maxChars?: number
  alsoSendText?: boolean
}

export interface AgentConfiguration {
  _id: string
  workspaceId: string
  userId?: string
  name: string
  description: string
  type: AgentType
  parentAgentId?: string
  modelConfig: ModelConfig
  availableTools: string[]
  toolPermissions: ToolPermission[]
  systemPrompt: string
  /** Operational rules: formatting, escalation, taboos (separate from persona / system prompt). */
  responseGuidelines?: string
  /** Structured persona metadata + preset voice (see `AgentVoicePreset`). */
  identity?: AgentIdentity
  /** Spoken voice (TTS) + when auto-replies go out as audio. `null` clears it. */
  voiceSettings?: AgentVoiceSettings | null
  /** Publisher-defined onboarding questions asked on first conversation (marketplace). */
  setupQuestions?: AgentSetupQuestion[]
  /** Conversation starters displayed on the agent chat home before the first message. */
  icebreakers?: AgentIcebreaker[]
  confirmationRequired: boolean
  allowSubAgents: boolean
  rateLimit: {
    maxExecutionsPerMinute: number
    maxExecutionsPerHour: number
  }
  isActive: boolean
  isTemplate: boolean
  category?: AgentCategory
  icon?: string
  attachedSkills?: SkillAttachment[]
  createdAt: string
  updatedAt: string
  /** When set by API, chat UI only lists agents that passed onboarding (see `hasCompletedOnboardingForChat`). */
  onboardingStatus?: string | null
  onboardingCompleted?: boolean | null
  /** Opt-in channels for dispatch / tools (e.g. `whatsapp`). */
  enabledChannels?: ("whatsapp" | "telegram" | "email")[]
  contextConfig?: AgentContextConfig
  scopeConfig?: AgentScopeConfig
  calendarAccess?: CalendarAccessConfig
  /** Background tasks (task runtime): no heartbeat runs while true. */
  tasksPaused?: boolean
  /** Token limits of background tasks; empty = platform default (per task) / none (daily). */
  taskBudget?: { maxTokensPerTask?: number; dailyTokens?: number }
  /** Periodic reminders on tasks stalled on a person (plan 5.2); no run when nothing is stalled. */
  taskReview?: { enabled: boolean; everyMinutes: number; instructions?: string }
  /** Runtime capability toggles — omitted fields default true on the server. */
  capabilities?: {
    internetAccess?: boolean
    workspaceDataAccess?: boolean
    knowledgeBaseAccess?: boolean
  }
  accessScope?: AgentAccessScope
  /** Set when this agent was cloned in from a published marketplace agent package. */
  marketplaceInstall?: {
    packageKey: string
    sourcePackageId: string
    installedFromVersion: string
  }
}

