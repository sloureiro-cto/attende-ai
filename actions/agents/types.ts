/** Which calendar(s) the agent's calendar tools may read from — never chosen by the model itself. */
export type CalendarAccessScope =
  | { type: "owner" }
  | { type: "workspace" }
  | { type: "users"; userIds: string[] }
  | { type: "googleCalendars"; calendarIds: string[] }

/**
 * Calendar tool access, default-deny: absent/`enabled: false` strips list_meetings,
 * get_meeting, list_google_calendar_events, schedule_meeting, update_meeting, cancel_meeting
 * entirely. A matching `AutomationBindingPolicy.calendarAccess` (per channel) overrides this
 * wholesale when set.
 */
export interface CalendarAccessConfig {
  enabled?: boolean
  /** Administrative permission — see and enumerate existing meetings' details. */
  canListMeetings?: boolean
  /** Check availability and create/update/cancel meetings. */
  canScheduleMeetings?: boolean
  scopes?: CalendarAccessScope[]
}

